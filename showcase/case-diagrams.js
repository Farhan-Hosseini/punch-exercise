/* Live diagrams for the case study: the machine state diagram, a run as a timeline, and the viewing geometry.
   Markup: parts/case-state.html, case-run.html, case-geometry.html (generated by build/case-diagrams/gen.mjs).
   Every diagram reads fully without this script. Here it only adds motion and the controls' behaviour, and it only
   writes classes, CSS variables, transform, opacity and stroke-dashoffset. Motion starts when a diagram scrolls into
   view (IntersectionObserver, root null, which respects the case study's own scroller) and stops when it leaves.
   Under prefers-reduced-motion nothing travels or draws in: states still change, instantly. */
(() => {
  'use strict'
  if (document.documentElement.dataset.embed === 'machine') return

  const reduce = matchMedia('(prefers-reduced-motion: reduce)')
  const calm = () => reduce.matches

  const stopped = () => new DOMException('stopped', 'AbortError')
  const wait = (ms, signal) => new Promise((resolve, reject) => {
    if (signal && signal.aborted) return reject(stopped())
    const t = setTimeout(resolve, ms)
    if (signal) signal.addEventListener('abort', () => { clearTimeout(t); reject(stopped()) }, { once: true })
  })

  // visible(true|false) whenever the element crosses the threshold
  function watch(el, threshold, fn) {
    let last = null
    const io = new IntersectionObserver((entries) => {
      for (const e of entries) {
        const on = e.isIntersecting && e.intersectionRatio >= threshold
        const gone = !e.isIntersecting
        if (on !== last) { last = on; fn(on, gone) } else if (gone) fn(false, true)
      }
    }, { threshold: [0, threshold] })
    io.observe(el)
    return io
  }

  // a sideways scroller: flags overflow on the scroller and the diagram, fades the clipped edges
  function scroller(root, sc, { fadeLeft = true, onUser } = {}) {
    const update = () => {
      const max = sc.scrollWidth - sc.clientWidth
      const over = max > 2
      sc.classList.toggle('is-overflow', over)
      root.classList.toggle('is-overflow', over)
      sc.style.setProperty('--fade-l', fadeLeft && sc.scrollLeft > 2 ? '32px' : '0px')
      sc.style.setProperty('--fade-r', over && sc.scrollLeft < max - 2 ? '40px' : '0px')
      sc.classList.toggle('is-scrolled', sc.scrollLeft > 2)
    }
    new ResizeObserver(update).observe(sc)
    sc.addEventListener('scroll', update, { passive: true })
    if (onUser) for (const type of ['pointerdown', 'wheel', 'touchstart']) sc.addEventListener(type, onUser, { passive: true })
    update()
    return update
  }

  /* ================================================================== 1. machine state diagram */
  function initState(root) {
    const svg = root.querySelector('.cd-state-svg')
    const nodes = [...root.querySelectorAll('.cd-node')]
    const edges = [...root.querySelectorAll('.cd-edge')]
    const byId = new Map(nodes.map((n) => [n.dataset.id, n]))
    const pulse = root.querySelector('.cd-pulse')
    const trails = new Map([...root.querySelectorAll('.cd-trail')].map((t) => [t.dataset.edge, t]))
    const replay = root.querySelector('[data-cd-replay]')
    const bars = root.querySelector('.cd-bars')
    const sc = root.querySelector('.cd-scroller')
    // on a narrow screen the board scrolls sideways; the reveal brings each state it reaches into view until the reader scrolls
    let touched = false
    scroller(root, sc, { onUser: () => { touched = true } })
    function follow(node, first) {
      if (touched || !node || sc.scrollWidth <= sc.clientWidth + 2) return
      const s = sc.getBoundingClientRect(), r = node.getBoundingClientRect()
      const left = first ? 0 : sc.scrollLeft + (r.left + r.width / 2) - (s.left + s.width / 2)
      sc.scrollTo({ left: Math.max(0, left), behavior: calm() ? 'auto' : 'smooth' })
    }

    /* tracing: a state's exits stay, everything else quiets */
    let traced = null
    function trace(id) {
      if (traced === id) return
      traced = id
      root.classList.toggle('is-tracing', !!id)
      for (const n of nodes) n.classList.remove('is-src', 'is-dst')
      for (const e of edges) {
        const on = !!id && e.dataset.from.split(' ').includes(id)
        e.classList.toggle('is-exit', on)
        if (on && e.dataset.to && e.dataset.to !== id) { const t = byId.get(e.dataset.to); if (t) t.classList.add('is-dst') }
      }
      if (id) byId.get(id).classList.add('is-src')
    }
    const focusedNode = () => { const a = document.activeElement; return a && svg.contains(a) && a.classList.contains('cd-node') ? a : null }
    svg.addEventListener('pointerover', (e) => {
      const n = e.target.closest('.cd-node')
      if (n) trace(n.dataset.id)
    })
    svg.addEventListener('pointerout', (e) => {
      const n = e.target.closest('.cd-node')
      if (n && !n.contains(e.relatedTarget)) { const f = focusedNode(); trace(f ? f.dataset.id : null) }
    })
    svg.addEventListener('focusin', (e) => { const n = e.target.closest('.cd-node'); if (n) trace(n.dataset.id) })
    svg.addEventListener('focusout', (e) => { if (!svg.contains(e.relatedTarget)) trace(null) })

    /* keyboard: one tab stop, arrows move between states by position */
    const cx = (n) => +n.dataset.cx, cy = (n) => +n.dataset.cy
    function neighbour(cur, key) {
      let list
      if (key === 'ArrowRight' || key === 'ArrowLeft') {
        list = nodes.filter((n) => Math.abs(cy(n) - cy(cur)) < 4 && (key === 'ArrowRight' ? cx(n) > cx(cur) : cx(n) < cx(cur)))
      } else {
        list = nodes.filter((n) => key === 'ArrowDown' ? cy(n) > cy(cur) + 4 : cy(n) < cy(cur) - 4)
      }
      list.sort((a, b) => (Math.abs(cy(a) - cy(cur)) - Math.abs(cy(b) - cy(cur))) * 1000 + Math.abs(cx(a) - cx(cur)) - Math.abs(cx(b) - cx(cur)))
      return list[0] || null
    }
    svg.addEventListener('keydown', (e) => {
      const cur = e.target.closest('.cd-node')
      if (!cur) return
      let next = null
      if (e.key.startsWith('Arrow')) next = neighbour(cur, e.key)
      else if (e.key === 'Home') next = nodes[0]
      else if (e.key === 'End') next = nodes[nodes.length - 1]
      else return
      e.preventDefault()
      if (next) { cur.tabIndex = -1; next.tabIndex = 0; next.focus() }
    })

    /* the pulse: credit, strike, verdict, result along the middle row, lighting each state it reaches */
    const HOPS = [['e1', 'M-02'], ['e2', 'M-03'], ['e5', 'M-04'], ['e7', 'M-05'], ['e8', 'M-06']]
    const AY = 268, HOP = 560, DWELL = 360
    let run = null, played = false
    function reset() {
      if (run) run.abort()
      run = null
      for (const a of pulse.getAnimations()) a.cancel()
      root.classList.remove('is-running', 'is-settled')
      for (const n of nodes) n.classList.remove('is-lit', 'is-passed')
      for (const t of trails.values()) t.classList.remove('is-drawn')
    }
    async function play() {
      reset()
      const ctl = new AbortController()
      run = ctl
      const sig = ctl.signal
      void root.offsetWidth
      root.classList.add('is-running')
      root.style.setProperty('--cd-hop', HOP + 'ms')
      try {
        let at = byId.get('M-01')
        follow(at, true)
        at.classList.add('is-lit')
        await wait(calm() ? 600 : 420, sig)
        for (const [eid, nid] of HOPS) {
          at.classList.replace('is-lit', 'is-passed')
          // the view travels with the pulse, so the next state is on screen when it lights
          follow(byId.get(nid))
          const trail = trails.get(eid)
          if (!calm() && trail) {
            trail.classList.add('is-drawn')
            const x1 = +trail.dataset.x1, x2 = +trail.dataset.x2
            pulse.animate([
              { transform: `translate(${x1}px, ${AY}px)`, opacity: 0 },
              { opacity: 1, offset: .14 },
              { opacity: 1, offset: .82 },
              { transform: `translate(${x2}px, ${AY}px)`, opacity: 0 },
            ], { duration: HOP, easing: 'cubic-bezier(.45, 0, .25, 1)', fill: 'forwards' })
            await wait(HOP, sig)
          } else {
            await wait(240, sig)
          }
          at = byId.get(nid)
          at.classList.add('is-lit')
          await wait(calm() ? 700 : DWELL, sig)
        }
        await wait(1500, sig)
        root.classList.add('is-settled')
        at.classList.replace('is-lit', 'is-passed')
      } catch (err) {
        if (err.name !== 'AbortError') throw err
      }
    }
    replay.addEventListener('click', () => { played = true; play() })
    // plays each time the diagram comes into view, and rests once it has left entirely. It watches the scroller, the
    // window the board is seen through: the canvas box is only as wide as that window, so a board scrolled sideways past it
    // would read as gone and reset the reveal halfway
    watch(sc, .35, (on, gone) => {
      if (on && !played) { played = true; play() }
      else if (gone && played) { played = false; reset() }
    })
    if (bars) {
      const io = watch(bars, .6, (on) => { if (on) { bars.classList.add('is-in'); io.disconnect() } })
    }
  }

  /* ================================================================== 2. a run, as a timeline */
  function initRun(root) {
    const evs = [...root.querySelectorAll('.cd-ev')]
    const btns = evs.map((li) => li.querySelector('.cd-ev-btn'))
    const playBtn = root.querySelector('[data-cd-play]')
    const prevBtn = root.querySelector('[data-cd-prev]')
    const nextBtn = root.querySelector('[data-cd-next]')
    const nowEl = root.querySelector('.cd-now')
    const nowT = root.querySelector('.cd-now-t')
    const sc = root.querySelector('.cd-run-scroller')
    const lanes = root.querySelector('.cd-lanes')
    const STEP = 2700
    const LABEL = { play: ['Play', 'Play the run'], pause: ['Pause', 'Pause the run'], replay: ['Replay', 'Replay the run'] }
    let i = 0, timer = 0, playing = false, autoplayed = false, touched = false

    scroller(root, sc, { fadeLeft: false, onUser: () => { touched = true; if (playing) stop() } })

    function setBtn(state) {
      playBtn.dataset.state = state
      playBtn.querySelector('.cd-play-t').textContent = LABEL[state][0]
      playBtn.setAttribute('aria-label', LABEL[state][1])
    }
    function bring(li) {
      const s = sc.getBoundingClientRect()
      if (!s.width) return
      const r = li.getBoundingClientRect()
      const left = s.left + lanes.getBoundingClientRect().width, right = s.right - 32
      let dx = 0
      if (r.left - 14 < left) dx = r.left - 14 - left
      else if (r.right > right) dx = r.right - right
      if (dx) sc.scrollTo({ left: sc.scrollLeft + dx, behavior: calm() ? 'auto' : 'smooth' })
    }
    function show(k, reveal) {
      i = Math.max(0, Math.min(evs.length - 1, k))
      root.style.setProperty('--i', i)
      evs.forEach((li, n) => {
        li.classList.toggle('is-past', n < i)
        if (n !== i) li.classList.remove('is-active')
      })
      const cur = evs[i]
      cur.classList.remove('is-active')
      void cur.offsetWidth // restart the miniature's moment
      cur.classList.add('is-active')
      btns.forEach((b, n) => { if (n === i) b.setAttribute('aria-current', 'step'); else b.removeAttribute('aria-current') })
      // announce the event only when the reader moved there, never on every autoplay step
      nowEl.setAttribute('aria-live', playing ? 'off' : 'polite')
      nowT.textContent = cur.querySelector('.cd-ev-t').textContent
      prevBtn.disabled = i === 0
      nextBtn.disabled = i === evs.length - 1
      if (!playing) setBtn(i === evs.length - 1 ? 'replay' : 'play')
      if (reveal) bring(cur)
    }
    function tick() {
      if (i >= evs.length - 1) { stop(); return }
      show(i + 1, true)
      if (i >= evs.length - 1) { stop(); return }
      timer = setTimeout(tick, STEP)
    }
    function play() {
      playing = true
      setBtn('pause')
      clearTimeout(timer)
      if (i >= evs.length - 1) show(0, true)
      timer = setTimeout(tick, STEP)
    }
    function stop() {
      playing = false
      clearTimeout(timer)
      setBtn(i >= evs.length - 1 ? 'replay' : 'play')
    }

    playBtn.addEventListener('click', () => { autoplayed = true; if (playing) stop(); else play() })
    prevBtn.addEventListener('click', () => { autoplayed = true; stop(); show(i - 1, true) })
    nextBtn.addEventListener('click', () => { autoplayed = true; stop(); show(i + 1, true) })
    btns.forEach((b, n) => {
      b.addEventListener('click', () => { autoplayed = true; stop(); show(n, true) })
      b.addEventListener('keydown', (e) => {
        if (e.key !== 'ArrowRight' && e.key !== 'ArrowLeft') return
        e.preventDefault()
        const k = Math.max(0, Math.min(evs.length - 1, n + (e.key === 'ArrowRight' ? 1 : -1)))
        autoplayed = true; stop(); show(k, true); btns[k].focus({ preventScroll: true })
      })
    })

    show(0, false)
    watch(sc, .3, (on) => {
      if (on && !autoplayed && !touched && !calm()) { autoplayed = true; show(0, true); play() }
      else if (!on && playing) stop()
    })
  }

  /* ================================================================== 3. viewing geometry */
  function initGeometry(root) {
    const ORDER = ['pad', 'back', 'decal', 'behind', 'far', 'child', 'all']
    const HOLD = 3600, HOLD_ALL = 4600
    const X = { all: 0, pad: 370, back: 550, decal: 850, behind: 950, far: 1150, child: 550 }
    const onEls = [...root.querySelectorAll('[data-on]')]
    const figs = [...root.querySelectorAll('.cd-g-fig')]
    const notes = [...root.querySelectorAll('.cd-geo-note')]
    const allBtn = root.querySelector('[data-cd-all]')
    const playBtn = root.querySelector('[data-cd-play]')
    const sc = root.querySelector('.cd-geo-scroller')
    const svg = root.querySelector('.cd-geo-svg')
    const vbW = svg.viewBox.baseVal.width
    let step = 'all', timer = 0, playing = false, userStopped = false, touched = false

    scroller(root, sc, { onUser: () => { touched = true } })

    function setBtn() {
      playBtn.dataset.state = playing ? 'pause' : 'play'
      playBtn.querySelector('.cd-play-t').textContent = playing ? 'Pause' : 'Step through'
      playBtn.setAttribute('aria-label', playing ? 'Pause the viewing positions' : 'Step through the viewing positions')
    }
    function bring(k) {
      if (sc.scrollWidth <= sc.clientWidth + 2) return
      const x = X[k] / vbW * svg.getBoundingClientRect().width
      sc.scrollTo({ left: Math.max(0, x - sc.clientWidth * .45), behavior: calm() ? 'auto' : 'smooth' })
    }
    function set(k, reveal) {
      step = k
      root.dataset.step = k
      const want = onEls.map((el) => el.dataset.on.split(' ').includes(k))
      // a step's own lines draw in again even when the previous step already showed them
      if (k !== 'all') onEls.forEach((el, n) => { if (want[n]) el.classList.remove('is-on') })
      void root.offsetWidth
      onEls.forEach((el, n) => el.classList.toggle('is-on', want[n]))
      for (const f of figs) f.classList.toggle('is-act', k !== 'all' && f.dataset.act.split(' ').includes(k))
      for (const b of notes) {
        const cur = b.dataset.step === k
        b.classList.toggle('is-current', cur)
        b.setAttribute('aria-pressed', cur ? 'true' : 'false')
      }
      allBtn.setAttribute('aria-pressed', k === 'all' ? 'true' : 'false')
      if (reveal) bring(k)
    }
    function advance() {
      const k = ORDER[(ORDER.indexOf(step) + 1) % ORDER.length]
      set(k, !touched)
      timer = setTimeout(advance, k === 'all' ? HOLD_ALL : HOLD)
    }
    function play() {
      playing = true
      setBtn()
      clearTimeout(timer)
      if (step === 'all') { set('pad', !touched); timer = setTimeout(advance, HOLD) }
      else timer = setTimeout(advance, HOLD)
    }
    function stop() {
      playing = false
      clearTimeout(timer)
      setBtn()
    }

    playBtn.addEventListener('click', () => {
      if (playing) { userStopped = true; stop() } else { userStopped = false; play() }
    })
    allBtn.addEventListener('click', () => { userStopped = true; stop(); set('all', true) })
    notes.forEach((b) => b.addEventListener('click', () => {
      userStopped = true
      stop()
      set(b.dataset.step === step ? 'all' : b.dataset.step, true)
    }))

    setBtn()
    watch(sc, .3, (on) => {
      if (on && !playing && !userStopped && !calm()) play()
      else if (!on && playing) stop()
    })
  }

  const INIT = { state: initState, run: initRun, geometry: initGeometry }
  function init() {
    for (const root of document.querySelectorAll('.cd[data-cd]')) {
      if (root.dataset.cdReady) continue
      root.dataset.cdReady = '1'
      root.classList.toggle('cd-motion', !calm())
      const fn = INIT[root.dataset.cd]
      if (fn) fn(root)
    }
  }
  reduce.addEventListener('change', () => {
    for (const root of document.querySelectorAll('.cd[data-cd]')) root.classList.toggle('cd-motion', !calm())
  })
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init)
  else init()
})()
