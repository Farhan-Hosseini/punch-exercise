// Lifts the glyph out of every exported Figma badge so the page can re-colour the circle.
// The path data and viewBox crop are the exported bytes; only the fill and stroke colours become tokens.
import { readFile, writeFile } from 'node:fs/promises'
const dir = new URL('../showcase/assets/figma/', import.meta.url)
const out = {}
for (const name of ['machine', 'city', 'country', 'global', 'energy', 'force', 'speed', 'acc', 'logo', 'play']) {
  const file = name === 'logo' ? 'logo-badge.svg' : name === 'play' ? 'cinema-play.svg' : `icon-${name}.svg`
  const svg = await readFile(new URL(file, dir), 'utf8')
  const rect = svg.match(/<rect([^>]*)\/>/)[1]
  const attrs = Object.fromEntries([...rect.matchAll(/([a-z-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]))
  const num = (k) => Number(attrs[k] || 0)
  const x = num('x'), y = num('y'), w = num('width'), h = num('height')
  const paths = [...svg.matchAll(/<path[^>]*\bd="([^"]+)"([^>]*)\/>/g)].map(m => {
    const attrs = m[2]
    const sw = (attrs.match(/stroke-width="([\d.]+)"/) || [])[1]
    return { d: m[1], stroke: /stroke="/.test(attrs), fill: /fill="white"/.test(attrs), sw: sw ? Number(sw) : 0 }
  })
  out[name] = { viewBox: `${x} ${y} ${w} ${h}`, paths }
}
const js = `/* Generated by tools/build-showcase-icons.mjs from the Figma exports in assets/figma. Do not edit. */\nwindow.GLYPHS = ${JSON.stringify(out)};\n`
await writeFile(new URL('../showcase/icons.js', import.meta.url), js)
console.log('glyphs', Object.keys(out).join(' '), (js.length / 1024).toFixed(1) + ' KB')
