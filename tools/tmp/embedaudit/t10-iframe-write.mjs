import { launch, conn, sleep } from './cdp.mjs'
const { port, chrome } = await launch({ w: 1440, h: 1000 })
const list = await (await fetch(`http://127.0.0.1:${port}/json/list`)).json()
const c = await conn(list.find((x) => x.type === 'page').webSocketDebuggerUrl)
await c.send('Runtime.enable'); await c.send('Page.enable')
await c.send('Page.navigate', { url: 'http://localhost:5770/' }); await sleep(3500)
await c.js(`localStorage.clear(); localStorage.setItem('punch-acc.v2', JSON.stringify({ page: 1, page2: 1, shared: 0, SENTINEL: 'keep' })); 1`)
await c.send('Page.navigate', { url: 'http://localhost:5770/' }); await sleep(6500)
console.log('after parent load (no toggling):', await c.js(`localStorage.getItem('punch-acc.v2')`))
const before = await c.js(`localStorage.getItem('punch-acc.v2')`)
// reset the sentinel shape so only the frame can change it
await c.js(`localStorage.setItem('punch-acc.v2', JSON.stringify({ page: 1, page2: 1, shared: 0, SENTINEL: 'keep' })); 1`)
await c.js(`window.showcase.mode('animation'); 1`); await sleep(6000)
const after = await c.js(`localStorage.getItem('punch-acc.v2')`)
console.log('frame src        :', await c.js(`document.getElementById('linkedFrame').getAttribute('src')`))
console.log('frame ready      :', await c.js(`(function(){try{return document.getElementById('linkedFrame').contentDocument.readyState}catch(e){return 'ERR'}})()`))
console.log('frame ran mobile :', await c.js(`(function(){try{var w=document.getElementById('linkedFrame').contentWindow;return JSON.stringify({punchApp:typeof w.punchApp,designSystem:typeof w.designSystem,PSec:typeof w.PSec,showcase:typeof w.showcase})}catch(e){return 'ERR'}})()`))
console.log('BEFORE animation :', before)
console.log('AFTER  animation :', after)
console.log('CHANGED BY FRAME :', before !== after)
console.log('showcase key     :', await c.js(`localStorage.getItem('punch-showcase.v5') ? 'written (parent saves on tab change - expected)' : 'absent'`))
console.log('errors:', JSON.stringify(c.errs.slice(0, 6)))
c.ws.close(); chrome.kill(); process.exit(0)
