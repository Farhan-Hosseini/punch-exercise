import { open, sleep } from './cdp.mjs'
const c = await open({ W: 1440, H: 1000 })
await c.send('Page.navigate', { url: 'http://localhost:5770/' }); await sleep(3000)
await c.js('localStorage.clear(); 1')
await c.send('Page.navigate', { url: 'http://localhost:5770/' }); await sleep(8000)
console.log('at rest (Mobile tab, nothing opened) :', JSON.stringify(await c.metrics()))
await c.js(`document.getElementById('openCase').click();1`); await sleep(9000)
console.log('case study open                      :', JSON.stringify(await c.metrics()))
await c.js(`document.getElementById('closeCase').click();1`); await sleep(4000)
console.log('case study closed again              :', JSON.stringify(await c.metrics()))
console.log('  #case iframe srcs:', JSON.stringify(await c.jsj(`[...document.querySelectorAll('#case iframe[data-embed]')].map(f=>f.getAttribute('src'))`)))
await sleep(8000)
console.log('closed, 8s later + GC                :', JSON.stringify(await c.metrics()))
console.log('errors:', c.errs.slice(0,8).join(' | ')||'(none)')
c.close()
