import { open, sleep } from './cdp.mjs'
const c = await open({ W: 1440, H: 1000 })
await c.send('Page.navigate', { url: 'http://localhost:5770/' }); await sleep(3000)
await c.js('localStorage.clear(); 1')
await c.send('Page.navigate', { url: 'http://localhost:5770/' }); await sleep(7000)
console.log('PunchFormat.ranks: machine rank for different scores')
for (const s of [0, 1000, 300000, 999999]) {
  console.log('   ranks(' + String(s).padStart(7) + ') =', JSON.stringify(await c.jsj(`window.PunchFormat.ranks(${s})`)))
}
console.log('   punchApp.score =', await c.js('window.punchApp.score'))
console.log('')
console.log('PSec cost:')
console.log('   pages           :', await c.js(`window.PSec.pages('machine').length + window.PSec.pages('phone').length`))
console.log('   applyAll() ms   :', await c.js(`(()=>{const t=performance.now(); window.PSec.applyAll(false); return +(performance.now()-t).toFixed(1)})()`))
console.log('   apply(phone,hit):', await c.js(`(()=>{const t=performance.now(); for(let i=0;i<20;i++) window.PSec.apply('phone','hit'); return +((performance.now()-t)/20).toFixed(2)})()`), 'ms each')
console.log('   punchApp.go x20 :', await c.js(`(()=>{const t=performance.now(); for(let i=0;i<10;i++){window.punchApp.go('feed');window.punchApp.go('ranks')} return +((performance.now()-t)/20).toFixed(1)})()`), 'ms per page change')
console.log('')
console.log('case study embeds after close:')
await c.js(`document.getElementById('openCase').click();1`); await sleep(6000)
await c.js(`document.getElementById('closeCase').click();1`); await sleep(2000)
console.log('   iframe srcs:', JSON.stringify(await c.jsj(`[...document.querySelectorAll('#case iframe[data-embed]')].map(f=>f.getAttribute('src'))`)))
const m = await c.metrics(); console.log('   metrics after close:', JSON.stringify(m))
console.log('errors:', c.errs.slice(0,8).join(' | ')||'(none)')
c.close()
